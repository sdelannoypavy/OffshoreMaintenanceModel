"""
Fluid policy of JFLP (CG), of JFLP-2 if `pairs` is not empty (pairs = same_pole_pairs(fd)), or of
JFLP+cuts if `cuts`, with fluid horizon `H` (Section "Fluid policies"). The columns generated for a
state are kept, for every period of the year and remaining horizon, and used to initialise the
restricted master problem of the next states. See make_fluid_policy (model.jl) for `cache_file` and
`log_solve`.
"""
function make_policy_jflp_cg(fd::FluidData; H::Int = 6,
                             pairs::Vector{Tuple{Int,Int}} = Tuple{Int,Int}[], cuts::Bool = false,
                             cache_file::Union{String,Nothing} = nothing, log_solve::Function = info -> nothing,
                             max_iter::Int = 50, time_limit_pricing::Float64 = 60.0)
    pools1 = Dict{Tuple{Int,Int},Vector{Column}}()   # (t0_cyc, H_eff) -> first-step columns found so far
    pools = Dict{Tuple{Int,Int},Vector{Column}}()    # (t0_cyc, H_eff) -> columns of the stages t ≥ 2 found so far
    function solve(x, k, t0_cyc, H_eff)
        pk = (t0_cyc, H_eff)
        col, info = solve_jflp_cg(fd, x, k, t0_cyc, H_eff; pairs = pairs, cuts = cuts,
                                  pool1 = get(pools1, pk, Column[]), pool = get(pools, pk, Column[]),
                                  max_iter = max_iter, time_limit_pricing = time_limit_pricing)
        pools1[pk] = unique(vcat(get(pools1, pk, Column[]), info.cols1))
        pools[pk] = unique(vcat(get(pools, pk, Column[]), info.cols))
        return col, merge(info, (t_milp = info.t_pricing, t_lp = info.t_master))
    end
    return make_fluid_policy(fd, solve; H = H, cache_file = cache_file, log_solve = log_solve)
end
