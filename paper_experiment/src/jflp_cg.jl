"""
    solve_jflp_cg(fd, x0, k0, t0_cyc, H; pairs, cuts, pool1, pool, ...)

Solves the Joint fluid LP (eq:fluid), its order-2 strengthening if `pairs` is not empty, or its
lift-and-project strengthening if `cuts`, by column generation, for the initial state (x0, k0), the
period of the year t0_cyc and the fluid horizon H. Returns the first-step joint action of largest
weight μ*_{b,1}, with statistics. `pool1` and `pool` are columns found for other states, used to
initialise B'_1 (those that satisfy the quota constraint in k0) and B'_t, t ≥ 2.

The order-2 LP is built with the transition probabilities cleaned at ORDER2_TRANSITION_TOL (model.jl)
instead of TRANSITION_TOL: with the exact transitions, its pairs have transition probabilities down
to 1e-16 and Gurobi cannot solve it for long fluid horizons.
"""
function solve_jflp_cg(fd::FluidData, x0::Vector{Int}, k0::Vector{Int}, t0_cyc::Int, H::Int;
                       pairs::Vector{Tuple{Int,Int}} = Tuple{Int,Int}[], kwargs...)
    isempty(pairs) && return _solve_jflp_cg(fd, x0, k0, t0_cyc, H; kwargs...)
    old_tol = TRANSITION_TOL
    global TRANSITION_TOL = ORDER2_TRANSITION_TOL
    try
        return _solve_jflp_cg(fd, x0, k0, t0_cyc, H; pairs = pairs, kwargs...)
    finally
        global TRANSITION_TOL = old_tol
    end
end

function _solve_jflp_cg(fd::FluidData, x0::Vector{Int}, k0::Vector{Int}, t0_cyc::Int, H::Int;
                        pairs::Vector{Tuple{Int,Int}} = Tuple{Int,Int}[], cuts::Bool = false,
                        pool1::Vector{Column} = Column[], pool::Vector{Column} = Column[],
                        max_iter::Int = 50, tol::Float64 = 1e-6,
                        time_limit_pricing::Float64 = 60.0, n_pool::Int = 10,
                        max_cut_rounds::Int = 10, max_cuts_per_round::Int = 20, cut_tol::Float64 = 1e-6,
                        verbose::Bool = false)
    t_begin = time()
    # Without the aggregation of Gurobi's presolve, the master LP of order 2 is solved fast and
    # reliably (with it, presolve wrongly declares the LP infeasible for long fluid horizons).
    params = isempty(pairs) ? Pair{String,Int}[] : ["Aggregate" => 0]
    master = build_master(fd, x0, k0, t0_cyc, H; pairs = pairs, lp_params = params)
    feasible_first(col) = all(column_kappa(col, p) <= k0[p] for p in 1:fd.inst.n_poles)
    push_first!(col) = (col in master.cols1 || !feasible_first(col)) ? false : (add_first_column!(fd, master, col); true)
    push_col!(col) = col in master.cols ? false : (add_column!(fd, master, col); true)

    # initial columns: the empty schedule (always in B(x0)), the repairs of a single component, and the pools
    push_first!(empty_column(fd)); foreach(push_first!, pool1)
    if H >= 2
        push_col!(empty_column(fd))
        for m in 1:fd.M
            FIRST_START_DAY + fd.d[m] - 1 <= fd.inst.T_period && push_col!(singleton_column(fd, m, FIRST_START_DAY))
        end
        foreach(push_col!, pool)
    end

    iterations = 0; converged = false; n_cuts = 0
    t_master = 0.0; t_pricing = 0.0; t_cuts = 0.0   # master LP solves, pricing MILPs, cut separation
    function column_generation!()
        converged = false
        for iter in 1:max_iter
            iterations += 1
            t_m = time(); solve_master!(master); t_m = time() - t_m; t_master += t_m
            lpv = objective_value(master.model)
            du = read_duals(master)   # every dual is read before any column is added
            n_new = 0
            t_p = time()
            col, rc, extras = solve_pricing_first(fd, master, du; time_limit = time_limit_pricing, n_pool = n_pool, tol = tol)
            if !isnothing(col) && rc < -tol
                push_first!(col) && (n_new += 1)
                foreach(c -> push_first!(c) && (n_new += 1), extras)
            end
            for t in 2:H
                col, rc, extras = solve_pricing_t(fd, master, du, t; time_limit = time_limit_pricing, n_pool = n_pool, tol = tol)
                (isnothing(col) || rc >= -tol) && continue
                push_col!(col) && (n_new += 1)
                foreach(c -> push_col!(c) && (n_new += 1), extras)
            end
            t_pricing += time() - t_p
            verbose && @printf("    iter %3d  master %.2fs  pricing %.2fs  new %3d  cuts %3d  LP %.6f\n",
                               iterations, t_m, time() - t_p, n_new, length(master.cuts), lpv)
            if n_new == 0
                converged = true
                return
            end
        end
        t_m = time(); solve_master!(master); t_master += time() - t_m
    end

    column_generation!()
    if cuts && H >= 2
        for round in 1:max_cut_rounds
            t_c = time()
            cands = violated_cuts(fd, master; tol = cut_tol)
            isempty(cands) && (t_cuts += time() - t_c; break)
            for c in cands[1:min(max_cuts_per_round, length(cands))]
                add_cut!(fd, master, c); n_cuts += 1
            end
            t_cuts += time() - t_c
            column_generation!()
        end
    end
    if !converged
        t_m = time(); solve_master!(master); t_master += time() - t_m
    end

    best = master.cols1[argmax(value.(master.μ1))]
    return best, (time = time() - t_begin, lp_value = objective_value(master.model),
                  t_master = t_master, t_pricing = t_pricing, t_cuts = t_cuts,
                  iterations = iterations, converged = converged, n_cuts = n_cuts,
                  n_columns = length(master.cols1) + length(master.cols),
                  cols1 = master.cols1, cols = master.cols)
end

