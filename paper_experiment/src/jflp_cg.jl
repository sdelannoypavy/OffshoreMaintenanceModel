"""
MILP formulation of B, or of B(x0) with the true cost c⊗(x0, ·) if `x0` is given (Appendix "MILP
formulation of the joint action cost minimization"), shared by both pricing problems. `obj` holds
the cost of the joint action, f(b) for B, c⊗(x0, b) for B(x0). The pricing problems add to it the
dual terms, written with the indicators of the local actions (`local_ind`) and of the pairs of local
actions (`pair_ind`).
"""
mutable struct PricingCore
    model::Model
    z::Vector{VariableRef}                      # z_m = 1 iff m is maintained
    ms::Dict{Tuple{Int,Int},VariableRef}        # (m, τ): the repair of m starts on day τ
    free::Matrix{VariableRef}                   # (p, τ): day τ is declared on substation p
    ksel::Dict{Tuple{Int,Int},VariableRef}      # (p, κ): κ days are declared on substation p
    y::Dict{Tuple{Int,Int},VariableRef}         # (m, κ): z_m ∧ ksel[pole(m), κ]
    w::Dict{NTuple{3,Int},VariableRef}          # (m1, m2, κ): z_{m1} ∧ z_{m2} ∧ ksel[pole, κ], created on demand
    starts::Vector{Vector{Int}}
    obj::AffExpr
end

function build_pricing_core(fd::FluidData; kcap::Vector{Int} = fd.K0,
                            x0::Union{Nothing,Vector{Int}} = nothing, time_limit::Float64 = 60.0,
                            n_pool::Int = 1)
    inst = fd.inst; M = fd.M; T = inst.T_period; K = inst.n_poles
    model = Model(() -> Gurobi.Optimizer(GRB_ENV))
    set_silent(model)
    set_time_limit_sec(model, time_limit)
    n_pool > 1 && set_optimizer_attribute(model, "PoolSolutions", n_pool)

    starts = [start_days(fd, m) for m in 1:M]
    z = @variable(model, [1:M], Bin)
    ms = Dict{Tuple{Int,Int},VariableRef}()
    for m in 1:M
        if isempty(starts[m])
            fix(z[m], 0.0; force = true)
            continue
        end
        for τ in starts[m]
            ms[(m, τ)] = @variable(model, binary = true)
        end
        @constraint(model, sum(ms[(m, τ)] for τ in starts[m]) == z[m])
    end
    ong(m, τ) = sum((ms[(m, s)] for s in starts[m] if s <= τ <= s + fd.d[m] - 1); init = AffExpr(0.0))   # under repair on day τ
    done(m, τ) = sum((ms[(m, s)] for s in starts[m] if τ >= s + fd.d[m]); init = AffExpr(0.0))         # repaired before day τ

    any_m = @variable(model, [1:K, 1:T], lower_bound = 0, upper_bound = 1)   # m^s_τ: maintenance day of substation p
    free = @variable(model, [1:K, 1:T], Bin)
    ksel = Dict{Tuple{Int,Int},VariableRef}()
    for p in 1:K, κ in qrange(kcap[p])
        ksel[(p, κ)] = @variable(model, binary = true)
    end
    for τ in FIRST_START_DAY:STEP:T
        # technician capacity, checked on the days of the start-day grid (the load is constant between them)
        @constraint(model, sum(fd.rho[m] * ong(m, τ) for m in 1:M) <= inst.R)
    end
    for p in 1:K
        @constraint(model, sum(ksel[(p, κ)] for κ in qrange(kcap[p])) == 1)
        @constraint(model, sum(free[p, τ] for τ in 1:T) == sum(κ * ksel[(p, κ)] for κ in qrange(kcap[p])))
        for m in fd.comps_of_pole[p], τ in 1:T
            @constraint(model, any_m[p, τ] >= ong(m, τ))
        end
    end

    obj = AffExpr(0.0)
    if isnothing(x0) || inst.simplified
        # f(b): penalty of the maintenance days that are not declared penalty-free, w = any_m ∧ free
        w_af = @variable(model, [1:K, 1:T], lower_bound = 0, upper_bound = 1)
        for p in 1:K, τ in 1:T
            @constraint(model, w_af[p, τ] <= free[p, τ])
            @constraint(model, w_af[p, τ] <= any_m[p, τ])
            pen = inst.poles[p].daily_penalty[τ]
            add_to_expression!(obj, pen, any_m[p, τ]); add_to_expression!(obj, -pen, w_af[p, τ])
        end
        if !isnothing(x0)
            # first step of the simplified model: c⊗(x0, b) = f(b) + replacement costs + failure costs (constant)
            add_to_expression!(obj, sum(failure_cost(fd, m, x0[m]) for m in 1:M))
            for m in 1:M
                add_to_expression!(obj, fd.cc[m], z[m])
            end
        end
    else
        # first step of the full model: true cost c⊗(x0, b), linearised.
        # L ≥ ℓ_m(ñ_{m,τ}) for every m of p (maximum of the losses), u = penalty of a maintenance day
        # that is not declared, v = penalty of a day without maintenance that is not declared
        L = @variable(model, [1:K, 1:T], lower_bound = 0)
        u = @variable(model, [1:K, 1:T], lower_bound = 0)
        v = @variable(model, [1:K, 1:T], lower_bound = 0)
        for p in 1:K, τ in 1:T
            for m in fd.comps_of_pole[p]
                ℓ0 = capacity_loss(fd, m, x0[m]); ℓ1 = capacity_loss(fd, m, 1)
                @constraint(model, L[p, τ] >= ℓ0 - (ℓ0 - ℓ1) * done(m, τ))
            end
            @constraint(model, u[p, τ] >= any_m[p, τ] - free[p, τ])
            @constraint(model, v[p, τ] >= L[p, τ] - any_m[p, τ] - free[p, τ])
            pen = inst.poles[p].daily_penalty[τ]
            add_to_expression!(obj, pen, u[p, τ]); add_to_expression!(obj, pen, v[p, τ])
        end
        for m in 1:M
            add_to_expression!(obj, fd.cc[m], z[m])
        end
    end

    # indicators of the local actions: y = z_m ∧ ksel[pole(m), κ]
    y = Dict{Tuple{Int,Int},VariableRef}()
    for m in 1:M
        p = fd.pole_of[m]
        for κ in qrange(kcap[p])
            yv = @variable(model, lower_bound = 0, upper_bound = 1)
            @constraint(model, yv <= z[m]); @constraint(model, yv <= ksel[(p, κ)])
            @constraint(model, yv >= z[m] + ksel[(p, κ)] - 1)
            y[(m, κ)] = yv
        end
    end
    return PricingCore(model, z, ms, free, ksel, y, Dict{NTuple{3,Int},VariableRef}(), starts, obj)
end


"Indicator of A_m(b) = (mode, κ), as an affine expression of the pricing variables (0 if κ is not allowed)."
function local_ind(core::PricingCore, fd::FluidData, m::Int, mode::Int, κ::Int)
    p = fd.pole_of[m]
    haskey(core.ksel, (p, κ)) || return AffExpr(0.0)
    return mode == 2 ? 1.0 * core.y[(m, κ)] : core.ksel[(p, κ)] - core.y[(m, κ)]
end

"Indicator of A_{m1}(b) = (d1, κ) and A_{m2}(b) = (d2, κ), for two components of a same pole."
function pair_ind(core::PricingCore, fd::FluidData, m1::Int, m2::Int, d1::Int, d2::Int, κ::Int)
    p = fd.pole_of[m1]
    haskey(core.ksel, (p, κ)) || return AffExpr(0.0)
    w = get!(core.w, (m1, m2, κ)) do
        wv = @variable(core.model, lower_bound = 0, upper_bound = 1)
        @constraint(core.model, wv <= core.y[(m1, κ)]); @constraint(core.model, wv <= core.y[(m2, κ)])
        @constraint(core.model, wv >= core.y[(m1, κ)] + core.y[(m2, κ)] - core.ksel[(p, κ)])
        wv
    end
    y1 = core.y[(m1, κ)]; y2 = core.y[(m2, κ)]; ks = core.ksel[(p, κ)]
    d1 == 2 && d2 == 2 && return 1.0 * w
    d1 == 2 && return y1 - w
    d2 == 2 && return y2 - w
    return ks - y1 - y2 + w
end

"Solve a pricing problem, returning its best column, its objective value, and the other columns of the solution pool with an objective < `pool_tol`."
function solve_core!(core::PricingCore, fd::FluidData; pool_tol::Float64 = -1e-6)
    @objective(core.model, Min, core.obj)
    optimize!(core.model)
    status = termination_status(core.model)
    if !(status == MOI.OPTIMAL || (status == MOI.TIME_LIMIT && has_values(core.model)))
        return nothing, Inf, Column[]
    end
    T = fd.inst.T_period; K = fd.inst.n_poles
    function column(r)
        start = zeros(Int, fd.M)
        for m in 1:fd.M
            value(core.z[m]; result = r) > 0.5 || continue
            for τ in core.starts[m]
                value(core.ms[(m, τ)]; result = r) > 0.5 && (start[m] = τ)
            end
        end
        return Column(start, [[τ for τ in 1:T if value(core.free[p, τ]; result = r) > 0.5] for p in 1:K])
    end
    extras = [column(r) for r in 2:result_count(core.model) if objective_value(core.model; result = r) < pool_tol]
    return column(1), objective_value(core.model), extras
end

"Duals of the restricted master LP, read before any column or cut is added."
struct Duals
    η::Float64
    ν::Dict{NTuple{3,Int},Float64}
    λ::Dict{NTuple{4,Int},Float64}
    ρG::Dict{NTuple{5,Int},Float64}               # duals of master.vfirst
    λG::Dict{NTuple{5,Int},Float64}
    π::Vector{Float64}                 # duals of master.cuts (≤ 0)
end

read_duals(master::Master) = Duals(dual(master.first),
    Dict(k => dual(c) for (k, c) in master.init), Dict(k => dual(c) for (k, c) in master.cons),
    Dict(k => dual(c) for (k, c) in master.vfirst), Dict(k => dual(c) for (k, c) in master.pcons),
    [dual(c.con) for c in master.cuts])

"""
First-step pricing problem (eq:pricing-first), extended with the duals of the order-2 initial
condition and of the t = 2 cuts: min over b ∈ B(x0) of the reduced cost of μ_{b,1}.
"""
function solve_pricing_first(fd::FluidData, master::Master, du::Duals;
                             time_limit::Float64 = 60.0, n_pool::Int = 1, tol::Float64 = 1e-6)
    x0 = master.x0; k0 = master.k0
    core = build_pricing_core(fd; kcap = k0, x0 = x0, time_limit = time_limit, n_pool = n_pool)
    if master.H >= 2
        for m in 1:fd.M
            p = fd.pole_of[m]
            for κ in qrange(k0[p]), mode in 1:2
                k_next = quota_next(1, master.t0_cyc, k0[p], κ, fd.K0[p])
                coef = sum(get(du.ν, (m, n, k_next), 0.0) * trans_prob(fd, m, n, x0[m], mode) for n in 1:fd.n_states[m])
                abs(coef) > 1e-12 && add_to_expression!(core.obj, coef, local_ind(core, fd, m, mode, κ))
            end
        end
        # order 2 and t = 2 cuts: both involve the joint distribution of a pair of local states at t = 2
        coefs = Dict{NTuple{6,Int},Float64}()   # (m1, m2, d1, d2, κ) -> coefficient, κ at t = 1
        for (g, (m1, m2)) in enumerate(master.pairs)
            p = fd.pole_of[m1]
            for κ in qrange(k0[p]), d1 in 1:2, d2 in 1:2
                c = 0.0
                for n1 in 1:(fd.n_states[m1] - 1)
                    ρv = get(du.ρG, (g, n1, d1, d2, κ), 0.0)
                    ρv == 0.0 && continue
                    c += ρv * trans_prob(fd, m1, n1, x0[m1], d1)
                end
                coefs[(m1, m2, d1, d2, κ, 0)] = get(coefs, (m1, m2, d1, d2, κ, 0), 0.0) + c
            end
        end
        for (i, c) in enumerate(master.cuts)
            c.t == 2 || continue
            p = fd.pole_of[c.m1]
            for κ in qrange(k0[p])
                quota_next(1, master.t0_cyc, k0[p], κ, fd.K0[p]) == c.k || continue
                for d1 in 1:2, d2 in 1:2
                    pr = trans_prob(fd, c.m1, c.n1, x0[c.m1], d1) * trans_prob(fd, c.m2, c.n2, x0[c.m2], d2)
                    pr == 0.0 && continue
                    coefs[(c.m1, c.m2, d1, d2, κ, 0)] = get(coefs, (c.m1, c.m2, d1, d2, κ, 0), 0.0) + du.π[i] * pr
                end
            end
        end
        for ((m1, m2, d1, d2, κ, _), c) in coefs
            abs(c) > 1e-12 && add_to_expression!(core.obj, c, pair_ind(core, fd, m1, m2, d1, d2, κ))
        end
    end
    col, val, extras = solve_core!(core, fd; pool_tol = du.η - tol)
    return col, val - du.η, extras
end

"""
Pricing problem (eq:pricing) at stage t ≥ 2, extended with the duals of the order-2 consistency
constraints and of the cuts of stage t: min over b ∈ B of the reduced cost of μ_{b,t}.
"""
function solve_pricing_t(fd::FluidData, master::Master, du::Duals, t::Int;
                         time_limit::Float64 = 60.0, n_pool::Int = 1, tol::Float64 = 1e-6)
    core = build_pricing_core(fd; time_limit = time_limit, n_pool = n_pool)
    for ((m, mode, κ, tt), λv) in du.λ
        tt == t && abs(λv) > 1e-12 && add_to_expression!(core.obj, λv, local_ind(core, fd, m, mode, κ))
    end
    for ((g, d1, d2, κ, tt), λv) in du.λG
        (tt == t && abs(λv) > 1e-12) || continue
        m1, m2 = master.pairs[g]
        add_to_expression!(core.obj, λv, pair_ind(core, fd, m1, m2, d1, d2, κ))
    end
    for (i, c) in enumerate(master.cuts)
        (c.t == t && abs(du.π[i]) > 1e-12) || continue
        # σ covers b iff κ_p(b) = κ and (A_{m1}(b) = (d1, κ) or A_{m2}(b) = (d2, κ))
        ind = local_ind(core, fd, c.m1, c.d1, c.κ) + local_ind(core, fd, c.m2, c.d2, c.κ) -
              pair_ind(core, fd, c.m1, c.m2, c.d1, c.d2, c.κ)
        add_to_expression!(core.obj, du.π[i], ind)
    end
    return solve_core!(core, fd; pool_tol = -tol)
end

