"""
Candidate cuts violated at the current solution, for the pairs of components of a same pole,
sorted by decreasing violation: (m1, m2, n1, n2, k, d1, d2, κ, t, violation).
"""
function violated_cuts(fd::FluidData, master::PaperMaster; tol::Float64 = 1e-6)
    qv = Dict(k => value(v) for (k, v) in master.q)
    μv = [value.(vs) for vs in master.μ]
    μ1v = value.(master.μ1)
    out = Tuple{Int,Int,Int,Int,Int,Int,Int,Int,Int,Float64}[]
    for (m1, m2) in same_pole_pairs(fd)
        p = fd.pole_of[m1]; K0 = fd.K0[p]; N1 = fd.n_states[m1]; N2 = fd.n_states[m2]
        for t in 2:master.H, k in qrange(K0)
            # τ⁺(n1, n2): bound on P(X_{m1,t} = (n1,k), X_{m2,t} = (n2,k))
            τ = zeros(N1, N2)
            if t == 2
                for (i, col) in enumerate(master.cols1)
                    μ1v[i] < 1e-12 && continue
                    first_next_k(fd, master, p, col) == k || continue
                    for n1 in 1:N1, n2 in 1:N2
                        τ[n1, n2] += μ1v[i] * pair_first_prob(fd, master, m1, m2, n1, n2, col)
                    end
                end
            else
                for (kp, κp) in quota_predecessors(t, master.t0_cyc, k, K0), d1 in 1:2, d2 in 1:2
                    v1 = [qv[(m1, n, d1, kp, κp, t - 1)] for n in 1:N1]
                    v2 = [qv[(m2, n, d2, kp, κp, t - 1)] for n in 1:N2]
                    (all(iszero, v1) || all(iszero, v2)) && continue
                    P1 = [trans_prob(fd, m1, n, np, d1) for n in 1:N1, np in 1:N1]
                    P2 = [trans_prob(fd, m2, n, np, d2) for n in 1:N2, np in 1:N2]
                    τ .+= P1 * min.(v1, v2') * P2'
                end
            end
            for κ in qrange(k), d1 in 1:2, d2 in 1:2
                σ = 0.0
                for (i, col) in enumerate(master.cols)
                    column_kappa(col, p) == κ || continue
                    (column_mode(col, m1) == d1 || column_mode(col, m2) == d2) || continue
                    σ += μv[i][t - 1]
                end
                for n1 in 1:N1, n2 in 1:N2
                    viol = qv[(m1, n1, d1, k, κ, t)] + qv[(m2, n2, d2, k, κ, t)] - σ - τ[n1, n2]
                    viol > tol && push!(out, (m1, m2, n1, n2, k, d1, d2, κ, t, viol))
                end
            end
        end
    end
    sort!(out; by = c -> -c[10])
    return out
end

"Add the cut (C) of the candidate `c` to the master LP, as a linear constraint (τ⁺ with min-linearisation variables for t ≥ 3)."
function add_cut_paper!(fd::FluidData, master::PaperMaster, c)
    m1, m2, n1, n2, k, d1, d2, κ, t = c[1:9]
    model = master.model; p = fd.pole_of[m1]; K0 = fd.K0[p]
    expr = master.q[(m1, n1, d1, k, κ, t)] + master.q[(m2, n2, d2, k, κ, t)]
    for (i, col) in enumerate(master.cols)   # σ
        column_kappa(col, p) == κ || continue
        (column_mode(col, m1) == d1 || column_mode(col, m2) == d2) || continue
        add_to_expression!(expr, -1.0, master.μ[i][t - 1])
    end
    if t == 2   # exact joint distribution of the two local states, from μ1
        for (i, col) in enumerate(master.cols1)
            first_next_k(fd, master, p, col) == k || continue
            prob = pair_first_prob(fd, master, m1, m2, n1, n2, col)
            prob == 0.0 && continue
            add_to_expression!(expr, -prob, master.μ1[i])
        end
    else        # τ⁺ propagated from t − 1, min(q1, q2) represented by z ≤ q1, z ≤ q2
        for (kp, κp) in quota_predecessors(t, master.t0_cyc, k, K0), a1 in 1:2, a2 in 1:2
            for n1p in 1:fd.n_states[m1]
                p1 = trans_prob(fd, m1, n1, n1p, a1)
                p1 == 0.0 && continue
                for n2p in 1:fd.n_states[m2]
                    p2 = trans_prob(fd, m2, n2, n2p, a2)
                    p1 * p2 == 0.0 && continue
                    zv = @variable(model, lower_bound = 0)
                    @constraint(model, zv <= master.q[(m1, n1p, a1, kp, κp, t - 1)])
                    @constraint(model, zv <= master.q[(m2, n2p, a2, kp, κp, t - 1)])
                    add_to_expression!(expr, -p1 * p2, zv)
                end
            end
        end
    end
    con = @constraint(model, expr <= 0)
    push!(master.cuts, PaperCut(m1, m2, n1, n2, k, d1, d2, κ, t, con))
end

# ─────────────────────────────────────────────────────────────────────────────
# Column generation (Algorithm 1), with the cutting-plane loop of the lift-and-project
# ─────────────────────────────────────────────────────────────────────────────

"""
    solve_fluid_cg_paper(fd, x0, k0, t0_cyc, H; pairs, cuts, ...)

Solves the Full fluid LP (eq:fluid), its order-2 strengthening if `pairs` is not empty, or its
lift-and-project strengthening if `cuts`, by column generation, and returns the first-step joint
action of largest weight μ1*_b (Section 3.4), with statistics. `pool1` and `pool` are columns
found for other states, used to initialise B'_1 (those that satisfy the quota constraint in k0)
and B'_t, t ≥ 2.

`p_tol` is the threshold below which the transition probabilities of the LP are moved onto the
diagonal (see PAPER_P_TOL). By default, it is PAPER_P_TOL (1e-8) for the Full fluid LP and the
lift-and-project, and ORDER2_P_TOL (1e-5) for the order-2 LP: with the exact transitions, the
order-2 master LP, whose pairs have transition probabilities down to 1e-16, cannot be solved by
Gurobi for long fluid horizons (numerical trouble), and the cleaning at 1e-5 changes the value of
the order-1 LP by about 0.3 % (measured on one_pole, H = 6).
"""
function solve_fluid_cg_paper(fd::FluidData, x0::Vector{Int}, k0::Vector{Int}, t0_cyc::Int, H::Int;
                              pairs::Vector{Tuple{Int,Int}} = Tuple{Int,Int}[],
                              p_tol::Float64 = isempty(pairs) ? PAPER_P_TOL : ORDER2_P_TOL, kwargs...)
    old_tol = PAPER_P_TOL
    p_tol == old_tol || set_paper_p_tol!(p_tol)
    try
        return _solve_fluid_cg_paper(fd, x0, k0, t0_cyc, H; pairs = pairs, kwargs...)
    finally
        p_tol == old_tol || set_paper_p_tol!(old_tol)
    end
end

function _solve_fluid_cg_paper(fd::FluidData, x0::Vector{Int}, k0::Vector{Int}, t0_cyc::Int, H::Int;
                              pairs::Vector{Tuple{Int,Int}} = Tuple{Int,Int}[], cuts::Bool = false, reduced::Bool = false,
                              pool1::Vector{Column} = Column[], pool::Vector{Column} = Column[],
                              max_iter::Int = 200, tol::Float64 = 1e-6,
                              time_limit_pricing::Float64 = 60.0, n_pool::Int = 10,
                              max_cut_rounds::Int = 10, max_cuts_per_round::Int = 20, cut_tol::Float64 = 1e-6,
                              lp_method::Union{Nothing,Int} = nothing,
                              lp_params::Union{Nothing,Vector{Pair{String,Int}}} = nothing,
                              pricing::Symbol = :auto, gap_tol::Float64 = 0.0, smoothing::Float64 = 0.0,
                              verbose::Bool = false)
    t_begin = time()
    # Defaults (measured on three_poles, QUOTA_STEP = 15, implemented_formulations.tex, Section
    # "Pricing problems of fluid_cg by blocks and by dynamic programming"). For the Joint fluid LP
    # (no pairs, no cuts): pricing by dynamic programming, and master LP by the primal simplex, which
    # restarts from the previous basis when columns are added (it stays primal feasible). With order-2
    # pairs or cuts: pricing MILP (the dynamic programming does not handle their duals), and dual
    # simplex (the cutting-plane loop adds rows, after which the basis stays dual feasible).
    plain = isempty(pairs) && !cuts
    lp_method = something(lp_method, plain ? 0 : 1)
    pricing = pricing == :auto ? (plain ? :dp : :milp) : pricing
    # gap_tol > 0: stop as soon as the Lagrangian bound LB is within gap_tol (relative) of the master LP
    # value. smoothing = α > 0: Wentges smoothing, see smoothed_duals. Both use the duals of the Joint
    # fluid LP only (no order-2 pairs, no cuts) for smoothing.
    smoothing > 0 && (!isempty(pairs) || cuts) && error("smoothing is only implemented for the Joint fluid LP")
    # pricing problems: MILP (build_pricing_core) or dynamic programming over the poles (pricing_dp.jl)
    pricing in (:milp, :dp) || error("pricing must be :milp or :dp")
    price_first = pricing == :dp ? solve_pricing_first_dp : solve_pricing_first_paper
    price_t = pricing == :dp ? solve_pricing_t_dp : solve_pricing_t_paper
    # Without the aggregation of Gurobi's presolve, the master LP of order 2 is solved fast and
    # reliably (with it, presolve wrongly declares the LP infeasible for long fluid horizons).
    params = isnothing(lp_params) ? (isempty(pairs) ? Pair{String,Int}[] : ["Aggregate" => 0]) : lp_params
    master = build_master_paper(fd, x0, k0, t0_cyc, H; pairs = pairs, lp_method = lp_method, lp_params = params, reduced = reduced)
    feasible_first(col) = all(column_kappa(col, p) <= k0[p] for p in 1:fd.inst.n_poles)
    push_first!(col) = (col in master.cols1 || !feasible_first(col)) ? false : (add_first_column!(fd, master, col); true)
    push_col!(col) = col in master.cols ? false : (add_column_paper!(fd, master, col); true)

    # Initial columns: the empty schedule (always in B(x0)), the singletons, and the columns of the pools.
    first_start = FIRST_START_DAY
    push_first!(empty_column(fd)); foreach(push_first!, pool1)
    if H >= 2
        push_col!(empty_column(fd))
        for m in 1:fd.M
            first_start + fd.d[m] - 1 <= fd.inst.T_period && push_col!(singleton_column(fd, m, first_start))
        end
        foreach(push_col!, pool)
    end

    iterations = 0; converged = false; n_cuts = 0; gap_stop = false
    lb_best = -Inf; center = nothing   # best Lagrangian bound, and the duals at which it was obtained
    # cumulated computing times: master LP solves, pricing MILPs (built and solved), cut separation
    t_master = 0.0; t_pricing = 0.0; t_cuts = 0.0
    function column_generation!()
        converged = false; gap_stop = false
        lb_best = -Inf; center = nothing   # the master changes when cuts are added
        for iter in 1:max_iter
            iterations += 1
            t_m = time(); solve_master!(master); t_m = time() - t_m; t_master += t_m
            lpv = objective_value(master.model)
            du = read_duals(master)   # every dual is read before any column is added
            n_new = 0
            t_p = time()
            # exact pricing at the duals of the master: new columns and Lagrangian bound
            # LB = LP + Σ_t min(0, rc*_t), valid since Σ_b μ_{b,t} = 1 at every t (eq:fluid-first, and
            # implied at t ≥ 2) and since the reduced costs of the variables q are ≥ 0 at the optimum
            lb = lpv
            t0 = time()
            col, rc, extras = price_first(fd, master, du; time_limit = time_limit_pricing,
                                          n_pool = n_pool, tol = tol)
            t_pricing += time() - t0
            isnothing(col) ? (lb = -Inf) : (lb += min(0.0, rc))
            if !isnothing(col) && rc < -tol
                push_first!(col) && (n_new += 1)
                foreach(c -> push_first!(c) && (n_new += 1), extras)
            end
            for t in 2:H
                t0 = time()
                col, rc, extras = price_t(fd, master, du, t; time_limit = time_limit_pricing,
                                          n_pool = n_pool, tol = tol)
                t_pricing += time() - t0
                isnothing(col) ? (lb = -Inf) : (lb += min(0.0, rc))
                (isnothing(col) || rc >= -tol) && continue
                push_col!(col) && (n_new += 1)
                foreach(c -> push_col!(c) && (n_new += 1), extras)
            end
            if lb > lb_best
                lb_best = lb; center = du
            end
            # Wentges smoothing: the pricing problems are also solved at α center + (1 − α) du, and
            # the columns found are added if their reduced cost at du is negative
            if smoothing > 0 && n_new > 0 && center !== du
                ds = smoothed_duals(center, du, smoothing)
                t0 = time()
                col, _, extras = price_first(fd, master, ds; time_limit = time_limit_pricing, n_pool = n_pool, tol = tol)
                for c in (isnothing(col) ? Column[] : vcat([col], extras))
                    reduced_cost_first(fd, master, du, c) < -tol && push_first!(c) && (n_new += 1)
                end
                for t in 2:H
                    col, _, extras = price_t(fd, master, ds, t; time_limit = time_limit_pricing, n_pool = n_pool, tol = tol)
                    for c in (isnothing(col) ? Column[] : vcat([col], extras))
                        reduced_cost_t(fd, du, c, t) < -tol && push_col!(c) && (n_new += 1)
                    end
                end
                t_pricing += time() - t0
            end
            if verbose
                @printf("    iter %3d  master %.2fs  pricing %.2fs  new %3d  cuts %3d  LP %.6f  LB %.6f\n",
                        iterations, t_m, time() - t_p, n_new, length(master.cuts), lpv, lb_best)
                flush(stdout)   # the log of a long solve is written as it goes
            end
            if n_new == 0
                converged = true
                return
            end
            if gap_tol > 0 && lpv - lb_best <= gap_tol * max(abs(lpv), 1e-9)
                gap_stop = true
                break
            end
        end
        t_m = time(); solve_master!(master); t_master += time() - t_m
    end

    column_generation!()
    if cuts && H >= 2
        for round in 1:max_cut_rounds
            t_c = time()
            cands = violated_cuts(fd, master; tol = cut_tol)
            isempty(cands) && (t_cuts += time() - t_c; break)
            for c in cands[1:min(max_cuts_per_round, length(cands))]
                add_cut_paper!(fd, master, c); n_cuts += 1
            end
            t_cuts += time() - t_c
            column_generation!()
        end
    end
    if !converged
        t_m = time(); solve_master!(master); t_master += time() - t_m
    end

    weights = value.(master.μ1)
    best = master.cols1[argmax(weights)]
    return best, (time = time() - t_begin, lp_value = objective_value(master.model), lower_bound = lb_best,
                  t_master = t_master, t_pricing = t_pricing, t_cuts = t_cuts,
                  iterations = iterations, converged = converged, gap_stop = gap_stop, n_cuts = n_cuts,
                  n_columns = length(master.cols1) + length(master.cols),
                  cols1 = master.cols1, cols = master.cols)
end

"""
Fluid policy (Section 3.4) of the Full fluid LP, of its order-2 strengthening (`pairs`) or of its
lift-and-project strengthening (`cuts`): (x, k, t_global) -> (Column, solve_time). Solutions are
cached (in memory and in `cache_file`). The columns found for a state are kept in pools, per
(t0_cyc, H_eff), and used to initialise the column generation of the next states.
"""
function make_policy_fluid_cg_paper(fd::FluidData; H::Int = 6,
                                    pairs::Vector{Tuple{Int,Int}} = Tuple{Int,Int}[], cuts::Bool = false, reduced::Bool = false,
                                    cache_file::Union{String,Nothing} = nothing,
                                    log_solve::Function = info -> nothing,
                                    max_iter::Int = 200, time_limit_pricing::Float64 = 60.0,
                                    pricing::Symbol = :auto, lp_method::Union{Nothing,Int} = nothing)
    T_total = fd.inst.n_years * N_PERIODS_PER_YEAR
    cache, next_cache_id = load_cache(cache_file)
    pools1 = Dict{Tuple{Int,Int},Vector{Column}}()
    pools = Dict{Tuple{Int,Int},Vector{Column}}()

    function policy(x::Vector{Int}, k::Vector{Int}, t_global::Int)
        t0_cyc = (t_global - 1) % N_PERIODS_PER_YEAR + 1
        H_eff = min(H, T_total - t_global + 1)
        key = (Tuple(x), Tuple(k), t0_cyc, H_eff)
        if !haskey(cache, key)
            pk = (t0_cyc, H_eff)
            col, info = solve_fluid_cg_paper(fd, x, k, t0_cyc, H_eff; pairs = pairs, cuts = cuts, reduced = reduced,
                                             pool1 = get(pools1, pk, Column[]), pool = get(pools, pk, Column[]),
                                             max_iter = max_iter, time_limit_pricing = time_limit_pricing,
                                             pricing = pricing, lp_method = lp_method)
            pools1[pk] = unique(vcat(get(pools1, pk, Column[]), info.cols1))
            pools[pk] = unique(vcat(get(pools, pk, Column[]), info.cols))
            cache[key] = (col.start, col.free_days, info.time, info.lp_value,
                          info.iterations, info.n_columns, info.converged)
            log_solve((key = key, time = info.time, lp_value = info.lp_value,
                       iterations = info.iterations, n_columns = info.n_columns,
                       converged = info.converged, t_milp = info.t_pricing, t_lp = info.t_master))
            append_cache_entry!(cache_file, next_cache_id, key, cache[key])
            return col, info.time
        end
        start, free_days = cache[key][1], cache[key][2]
        return Column(start, free_days), 0.0
    end
    return policy
end

# ─────────────────────────────────────────────────────────────────────────────
# Schedule for the true cost of the paper (used by the policy of the Compact fluid LP)
# ─────────────────────────────────────────────────────────────────────────────

"""
    schedule_paper(fd, x0, k0, maintain)

Admissible joint action in the state (x0, k0) that maintains the components of `maintain` that
fit: every one starts on the earliest day of the start-day grid compatible with the technician
capacity (the most degraded first), which is optimal for the true cost of the paper since an
earlier repair only shortens the days of capacity loss. The declared penalty-free days of each
pole are then placed on its days of largest loss, maintenance days first (loss 1), their number
being the largest multiple of QUOTA_STEP at most k0[p] and at most the number of days with a
positive loss.
"""
function schedule_paper(fd::FluidData, x0::Vector{Int}, k0::Vector{Int}, maintain::AbstractVector{Bool})
    inst = fd.inst; M = fd.M; T = inst.T_period; K = inst.n_poles
    last_start = [T - fd.d[m] + 1 - inst.margin for m in 1:M]
    first_start = FIRST_START_DAY
    cand = [m for m in 1:M if maintain[m] && last_start[m] >= first_start]
    sort!(cand; by = m -> (-capacity_loss(fd, m, x0[m]), -fd.rho[m]))
    start = zeros(Int, M); demand = zeros(T)
    for m in cand
        for τ in first_start:QUOTA_STEP:last_start[m]
            if all(demand[s] + fd.rho[m] <= inst.R + 1e-9 for s in τ:(τ + fd.d[m] - 1))
                start[m] = τ
                for s in τ:(τ + fd.d[m] - 1); demand[s] += fd.rho[m]; end
                break
            end
        end
    end
    free_days = Vector{Vector{Int}}(undef, K)
    for p in 1:K
        loss = zeros(T)
        for τ in 1:T
            ms = fd.comps_of_pole[p]
            if any(start[m] > 0 && start[m] <= τ <= start[m] + fd.d[m] - 1 for m in ms)
                loss[τ] = 1.0
            else
                loss[τ] = maximum(capacity_loss(fd, m, (start[m] > 0 && τ >= start[m] + fd.d[m]) ? 1 : x0[m]) for m in ms)
            end
        end
        n_pos = count(>(1e-12), loss)
        κ = QUOTA_STEP * div(min(k0[p], n_pos), QUOTA_STEP)
        free_days[p] = sort(sortperm(loss; rev = true)[1:κ])
    end
    return Column(start, free_days)
end

