# fluid_cg_paper.jl
#
# Full fluid LP of Section 3.2 of paper.tex, its order-2 strengthening of Section 4.2 and its
# lift-and-project strengthening of Section 4.3, solved by column generation, with the fluid
# policy of Section 3.4 (joint action of largest weight μ*_{b,1}). This file follows the paper
# exactly when QUOTA_STEP = 1 (default, instances.jl). With QUOTA_STEP = 15, the quota and the
# start days are discretised in steps of 15 days.
#
#   - Local state of component m: x = (n, k), n its degradation state and k the remaining quota
#     of its pole. Local action: a = (mode, κ), mode = 1 (not maintained) or 2 (maintained) and
#     κ the number of penalty-free days declared on its pole.
#   - First time step (t = 1): variables μ1_b for b ∈ B'_1 ⊆ B(x0), with the TRUE cost c⊗(x0, b)
#     of the paper (true_period_cost, fluid_lp_cg.jl), constraint Σ_b μ1_b = 1 (eq:fluid-first)
#     and initial condition (eq:fluid-initial), which gives the distribution of the local states
#     at t = 2 from the distribution of B_1.
#   - Time steps t ≥ 2: variables q^m_{x,a,t} with the separable approximation of the cost
#     c̃_m(x, a) = δ Rc_m + (T − κ) π ℓ_m(n) (eq:intro-failure-cost), and μ_{b,t} for b ∈ B'_t ⊆ B
#     with the joint action cost f(b) = Mc (column_penalty, fluid_lp_cg.jl). Constraints: local
#     flow (eq:fluid-flow), consistency (eq:fluid-consistency), local state-action constraint
#     κ ≤ k (eq:fluid-admissible, enforced by creating q only for κ ≤ k) and quota consistency
#     (eq:fluid-copies).
#   - Order 2 (Section 4.2, `pairs` non empty): for every pair G = (m1, m2) of components of a
#     same pole, variables q^G_{x_G,a_G,t}, t ≥ 2, with the cost of order 2
#     Fc_G = −(T − κ) π min(ℓ_{m1}(n1), ℓ_{m2}(n2)), and the constraints (eq:order-k-initial),
#     (eq:order-k-flow), (eq:order-k-action), (eq:order-k-marg); the quota constraints
#     (eq:order-k-admissible) and (eq:order-k-copies) are enforced by indexing q^G by the single
#     quota k and number of declared days κ of the pole, with κ ≤ k. Only the pairs of a same
#     pole are used (implemented_formulations.tex).
#   - Lift-and-project (Section 4.3, `cuts = true`): cuts (C) of Proposition 11, generalised to
#     the local actions, for the pairs of components of a same pole,
#       q^{m1}_{x1,a1,t} + q^{m2}_{x2,a2,t} ≤ Σ_{b | A_{m1}(b) = a1 or A_{m2}(b) = a2} μ_{b,t} + τ⁺,
#     with τ⁺ = Σ p_{m1} p_{m2} min(q^{m1}_{x1',a1',t−1}, q^{m2}_{x2',a2',t−1}) for t ≥ 3, and, for
#     t = 2, the exact joint distribution Σ_b μ1_b p_{m1}(x1 | x0, A_{m1}(b)) p_{m2}(x2 | x0, A_{m2}(b))
#     of the two local states (the state at t = 1 is fixed). The cuts are generated by a
#     cutting-plane loop. The columns added after a cut enter its right-hand side, and the duals of
#     the cuts enter the pricing problems, so that the column generation stays exact.
#   - Column generation (Algorithm 1): first-step pricing problem (eq:pricing-first) with the true
#     cost linearised by auxiliary variables, and pricing problem (eq:pricing) at every t ≥ 2,
#     both extended with the duals of the order-2 constraints and of the cuts. The pricing MILP
#     indexes the declared days by blocks of QUOTA_STEP days when this is exact (pricing_block_len).
#     For the Joint fluid LP (no pairs, no cuts), the pricing problems are solved by default by
#     dynamic programming over the poles (pricing_dp.jl) and the master LP by the primal simplex.
#     Options: Lagrangian stopping rule (gap_tol) and Wentges smoothing (smoothing), off by default.

using JuMP, Gurobi, Printf

# ─────────────────────────────────────────────────────────────────────────────
# Costs and dynamics of the paper
# ─────────────────────────────────────────────────────────────────────────────

"Daily penalty π of the instance, which the separable approximation of the paper assumes constant."
function constant_daily_penalty(fd::FluidData)
    pens = unique(vcat([p.daily_penalty for p in fd.inst.poles]...))
    length(pens) == 1 || error("the cost approximation of the paper assumes a constant daily penalty")
    return pens[1]
end

"Separable approximation c̃_m(x, a) of the paper: δ Rc_m + (T − κ) π ℓ_m(n), with x = (n, k) and a = (mode, κ)."
paper_local_cost(fd::FluidData, m::Int, n::Int, mode::Int, κ::Int) =
    (mode == 2 ? fd.cc[m] : 0.0) + (fd.inst.T_period - κ) * constant_daily_penalty(fd) * capacity_loss(fd, m, n)

"Failure cost of order 2 Fc_G = −(T − κ) π min(ℓ_{m1}(n1), ℓ_{m2}(n2)) of a pair of components of a same pole."
paper_pair_cost(fd::FluidData, m1::Int, m2::Int, n1::Int, n2::Int, κ::Int) =
    -(fd.inst.T_period - κ) * constant_daily_penalty(fd) * min(capacity_loss(fd, m1, n1), capacity_loss(fd, m2, n2))

"Pairs of distinct components of a same pole."
same_pole_pairs(fd::FluidData) =
    [(cs[i], cs[j]) for cs in fd.comps_of_pole for i in eachindex(cs) for j in (i + 1):length(cs)]

"""
Approximation of the cost of the paper (eq:cost_approx at order 1, cost of order 2 if `pairs` is
given), at the realised state `x` and joint action `col`: the cost model actually optimised by the
fluid LPs at t ≥ 2, reported as `lp_cost` by run_experiment.jl.
"""
function paper_approx_cost(fd::FluidData, x::Vector{Int}, col::Column;
                           pairs::Vector{Tuple{Int,Int}} = Tuple{Int,Int}[])
    c = column_penalty(fd, col) + sum(paper_local_cost(fd, m, x[m], column_mode(col, m),
                                                       column_kappa(col, fd.pole_of[m])) for m in 1:fd.M)
    for (m1, m2) in pairs
        c += paper_pair_cost(fd, m1, m2, x[m1], x[m2], column_kappa(col, fd.pole_of[m1]))
    end
    return c
end

# Transition probabilities below PAPER_P_TOL are moved onto the diagonal (clean_transitions,
# fluid_lp_cg.jl) in the data of the LPs of this file and of compact_paper.jl, the simulator
# keeping the exact transitions. Without this, the order-2 LP, whose transitions of the pairs
# are products of two probabilities, has coefficients down to 1e-16 and Gurobi fails to solve it
# (numerical trouble). Can be changed with `set_paper_p_tol!` before solving.
PAPER_P_TOL = 1e-8
const ORDER2_P_TOL = 1e-5   # threshold used by the order-2 LP (see solve_fluid_cg_paper)
const PAPER_P_CACHE = Dict{Tuple{UInt,Int},Matrix{Float64}}()

"Set the threshold below which the transition probabilities of the LPs are moved onto the diagonal."
set_paper_p_tol!(tol::Float64) = (global PAPER_P_TOL = tol; empty!(PAPER_P_CACHE); tol)

"Transition matrix (to, from) of component m used by the LPs, cleaned at PAPER_P_TOL."
paper_P(fd::FluidData, m::Int) =
    get!(() -> clean_transitions(fd.P[m]; tol = PAPER_P_TOL), PAPER_P_CACHE, (objectid(fd), m))

"Transition probability p_m(n | n', mode) of the degradation state over one period, used by the LPs."
trans_prob(fd::FluidData, m::Int, n::Int, np::Int, mode::Int) =
    mode == 1 ? paper_P(fd, m)[n, np] : (n == 1 ? 1.0 : 0.0)

"Quota dynamics φ_t(k, κ) (eq:intro-quota-dynamics) of a pole with annual quota K0, at the stage t of the fluid horizon."
quota_next(t::Int, t0_cyc::Int, k::Int, κ::Int, K0::Int) =
    stage_cyc(t, t0_cyc) == N_PERIODS_PER_YEAR ? K0 : k - κ

"(k', κ') at stage t−1 from which the quota of a pole becomes k at stage t (flow constraints)."
function quota_predecessors(t::Int, t0_cyc::Int, k::Int, K0::Int)
    if stage_cyc(t - 1, t0_cyc) == N_PERIODS_PER_YEAR
        return k == K0 ? [(kp, κp) for kp in qrange(K0) for κp in qrange(kp)] : Tuple{Int,Int}[]
    end
    return [(k + κp, κp) for κp in 0:QUOTA_STEP:(K0 - k)]
end

"True cost c⊗(x0, b) of a first-step column."
first_step_cost(fd::FluidData, x0::Vector{Int}, col::Column) = sum(true_period_cost(fd, x0, col))

# ─────────────────────────────────────────────────────────────────────────────
# Restricted master LP
# ─────────────────────────────────────────────────────────────────────────────

mutable struct PaperCut
    m1::Int; m2::Int; n1::Int; n2::Int; k::Int; d1::Int; d2::Int; κ::Int; t::Int
    con::ConstraintRef
end

mutable struct PaperMaster
    model::Model
    H::Int
    x0::Vector{Int}
    k0::Vector{Int}
    t0_cyc::Int
    first::ConstraintRef                          # Σ_b μ1_b = 1
    init::Dict{NTuple{3,Int},ConstraintRef}       # (m, n, k) -> initial condition at t = 2
    cons::Dict{NTuple{4,Int},ConstraintRef}       # (m, mode, κ, t) -> consistency, t ≥ 2
    q::Dict{NTuple{6,Int},VariableRef}            # (m, n, mode, k, κ, t), t ≥ 2, κ ≤ k
    μ1::Vector{VariableRef}
    cols1::Vector{Column}
    μ::Vector{Vector{VariableRef}}                # μ[col_id][t - 1], t = 2..H
    cols::Vector{Column}
    pairs::Vector{Tuple{Int,Int}}                 # order 2: pairs of components of a same pole
    qG::Dict{NTuple{8,Int},VariableRef}           # (g, n1, n2, k, d1, d2, κ, t), t ≥ 2, κ ≤ k
    pinit::Dict{NTuple{4,Int},ConstraintRef}      # (g, n1, n2, k) -> initial condition of order 2 at t = 2
    vfirst::Dict{NTuple{5,Int},ConstraintRef}     # (g, n1, d1, d2, κ1) -> v = Σ_b p_{m1} μ1_b (first step of the kernel of the pair)
    pcons::Dict{NTuple{5,Int},ConstraintRef}      # (g, d1, d2, κ, t) -> consistency of order 2
    cuts::Vector{PaperCut}
    lp_method::Int                                # Gurobi Method used to solve the master LP
end

"Degradation states of every component reachable from x0 at the stages 1..H of the LP (a maintenance resets to 1): S[m][t]."
function reachable_states(fd::FluidData, x0::Vector{Int}, H::Int)
    S = [[Set{Int}() for _ in 1:H] for _ in 1:fd.M]
    for m in 1:fd.M
        S[m][1] = Set([x0[m]])
        for t in 2:H
            S[m][t] = Set(n for np in S[m][t - 1] for mode in 1:2 for n in 1:fd.n_states[m]
                          if trans_prob(fd, m, n, np, mode) > 0)
        end
    end
    return S
end

"""
    build_master_paper(fd, x0, k0, t0_cyc, H; pairs, reduced)

Restricted master LP of the Full fluid LP (eq:fluid), or of the order-2 fluid LP (eq:order-k,
k = 2) restricted to the groups of `pairs` if `pairs` is not empty, for the initial state
(x0, k0), without any column (added by `add_first_column!` and `add_column_paper!`).

`reduced = true` (order 2 only) writes the same LP without its linearly dependent rows and without
the variables of the pairs of states that cannot be reached from x0, which are 0 in every feasible
solution. In floating point, the dependent rows become small inconsistencies that make the master
LP highly degenerate and slow to solve. In every pole whose pairs (first component, m) are all in
`pairs`:
  - the quota consistency (eq:fluid-copies) is implied by the marginalisation onto the first
    component, and is not written,
  - for every pair without the first component, one marginalisation row of m2 per (k, κ, t) is
    implied by the other pairs (the pair closes a cycle), and is not written,
  - for every component m other than the first, the sum over n of its initial condition and flow
    rows at (k, t) is implied by the first component, and the row of its highest reachable state
    is not written; the sum over the mode of its consistency rows at (κ, t) is implied as well,
    and its rows mode = 1 are not written.
The rows of the pairs dropped in every case (highest state of m1 or of m2) are taken at the highest
reachable state instead of N, otherwise the dependency remains.
"""
function build_master_paper(fd::FluidData, x0::Vector{Int}, k0::Vector{Int}, t0_cyc::Int, H::Int;
                            pairs::Vector{Tuple{Int,Int}} = Tuple{Int,Int}[], lp_method::Int = 1,
                            lp_params::Vector{Pair{String,Int}} = Pair{String,Int}[],
                            reduced::Bool = false, reduce_rows::Bool = reduced, reduce_states::Bool = reduced)
    M = fd.M
    reduced = reduced && !isempty(pairs)
    # reachable states (all the states if not reduced) and highest reachable state, per m and t
    S = reduced && reduce_states ? reachable_states(fd, x0, H) : [[Set(1:fd.n_states[m]) for _ in 1:H] for m in 1:M]
    top(m, t) = maximum(S[m][t])
    # poles whose pairs (first component, m) are all in `pairs`, and components other than their first
    pairset = Set(Set(pr) for pr in pairs)
    first_of = [fd.comps_of_pole[p][1] for p in 1:fd.inst.n_poles]
    covered = [reduced && reduce_rows && all(Set((first_of[p], m)) in pairset for m in fd.comps_of_pole[p][2:end])
               for p in 1:fd.inst.n_poles]
    implied(m) = covered[fd.pole_of[m]] && m != first_of[fd.pole_of[m]]
    model = Model(() -> Gurobi.Optimizer(GRB_ENV))
    set_silent(model)
    set_optimizer_attribute(model, "Method", 1)   # dual simplex: vertex solutions, see build_master
    for (name, val) in lp_params
        set_optimizer_attribute(model, name, val)
    end
    if !isempty(pairs)
        # The order-2 LP carries probabilities of the failure states down to 1e-5 against costs up to
        # about 70 per period: with Gurobi's default tolerances (1e-6), the optimal value is only
        # accurate to about 1% (measured on one_pole, H = 2, where the original and the reduced LP
        # differ by 1% with the default tolerances and agree to 1e-8 with these).
        set_optimizer_attribute(model, "FeasibilityTol", 1e-9)
        set_optimizer_attribute(model, "OptimalityTol", 1e-9)
    end

    q = Dict{NTuple{6,Int},VariableRef}()
    obj = AffExpr(0.0)
    for m in 1:M, t in 2:H, n in 1:fd.n_states[m], mode in 1:2
        K0 = fd.K0[fd.pole_of[m]]
        for k in qrange(K0), κ in qrange(k)          # κ ≤ k: local state-action constraint (eq:fluid-admissible)
            v = @variable(model, lower_bound = 0)
            q[(m, n, mode, k, κ, t)] = v
            add_to_expression!(obj, paper_local_cost(fd, m, n, mode, κ), v)
        end
    end

    first = @constraint(model, AffExpr(0.0) == 1.0)   # Σ_b μ1_b = 1 (eq:fluid-first)

    # initial condition (eq:fluid-initial): Σ_a q^m_{(n,k),a,2} = Σ_b p_m((n,k) | x0_m, A_m(b)) μ1_b
    init = Dict{NTuple{3,Int},ConstraintRef}()
    if H >= 2
        for m in 1:M, n in 1:fd.n_states[m], k in qrange(fd.K0[fd.pole_of[m]])
            implied(m) && n == top(m, 2) && continue   # reduced: implied by the first component
            init[(m, n, k)] = @constraint(model,
                sum(q[(m, n, mode, k, κ, 2)] for mode in 1:2, κ in qrange(k)) == 0)
        end
    end

    # local flow constraints (eq:fluid-flow), t ≥ 3
    for t in 3:H, m in 1:M
        K0 = fd.K0[fd.pole_of[m]]
        for n in 1:fd.n_states[m], kn in qrange(K0)
            implied(m) && n == top(m, t) && continue   # reduced: implied by the first component
            lhs = sum(q[(m, n, mode, kn, κ, t)] for mode in 1:2, κ in qrange(kn))
            preds = quota_predecessors(t, t0_cyc, kn, K0)
            rhs = AffExpr(0.0)
            for np in 1:fd.n_states[m], mode in 1:2
                prob = trans_prob(fd, m, n, np, mode)
                prob == 0.0 && continue
                for (kp, κp) in preds
                    add_to_expression!(rhs, prob, q[(m, np, mode, kp, κp, t - 1)])
                end
            end
            @constraint(model, lhs == rhs)
        end
    end

    # consistency (eq:fluid-consistency), t ≥ 2: Σ_x q^m_{x,a,t} = Σ_{b | A_m(b) = a} μ_{b,t}
    cons = Dict{NTuple{4,Int},ConstraintRef}()
    for t in 2:H, m in 1:M, mode in 1:2
        implied(m) && mode == 1 && continue   # reduced: implied by the first component and mode = 2
        K0 = fd.K0[fd.pole_of[m]]
        for κ in qrange(K0)
            cons[(m, mode, κ, t)] = @constraint(model,
                sum(q[(m, n, mode, k, κ, t)] for n in 1:fd.n_states[m], k in κ:QUOTA_STEP:K0) == 0)
        end
    end

    # quota consistency (eq:fluid-copies), t ≥ 2
    for p in 1:fd.inst.n_poles, m in fd.comps_of_pole[p][2:end], t in 2:H
        covered[p] && continue   # reduced: implied by the marginalisation onto the first component
        m1 = fd.comps_of_pole[p][1]; K0 = fd.K0[p]
        for k in qrange(K0), κ in qrange(k)
            @constraint(model,
                sum(q[(m, n, mode, k, κ, t)] for n in 1:fd.n_states[m], mode in 1:2) ==
                sum(q[(m1, n, mode, k, κ, t)] for n in 1:fd.n_states[m1], mode in 1:2))
        end
    end

    # ── order 2 (Section 4.2), pairs of components of a same pole ─────────────────
    qG = Dict{NTuple{8,Int},VariableRef}()
    pinit = Dict{NTuple{4,Int},ConstraintRef}()
    vfirst = Dict{NTuple{5,Int},ConstraintRef}()
    pcons = Dict{NTuple{5,Int},ConstraintRef}()
    for (g, (m1, m2)) in enumerate(pairs)
        p = fd.pole_of[m1]; K0 = fd.K0[p]
        fd.pole_of[m2] == p || error("order 2: only pairs of a same pole are supported")
        # reduced: a pair without the first component of its pole closes a cycle of pairs
        cyc = covered[p] && first_of[p] ∉ (m1, m2)
        for t in 2:H, n1 in S[m1][t], n2 in S[m2][t], k in qrange(K0), d1 in 1:2, d2 in 1:2, κ in qrange(k)
            v = @variable(model, lower_bound = 0)
            qG[(g, n1, n2, k, d1, d2, κ, t)] = v
            add_to_expression!(obj, paper_pair_cost(fd, m1, m2, n1, n2, κ), v)
        end
        # The rows of the initial condition, of the flow and of the consistency of order 2 that are
        # implied by the others and by the marginalisation constraints are not written: summing the
        # rows of a pair over n2 (or d2) gives the row of m1, and over n1 (or d1) the row of m2. In
        # floating point, these exact dependencies become small inconsistencies (Σ_{n2} p1 p2 is not
        # exactly p1), which make the LP numerically unstable. Only the rows n1 < top(m1), n2 < top(m2)
        # (and (d1, d2) = (2, 2)) are kept, which gives the same feasible set, top being the highest
        # state N (the highest reachable state if `reduced`).
        # The product kernel p_{m1} p_{m2} of the pairs has coefficients down to 1e-16, which makes the
        # LP numerically intractable. It is therefore applied in two steps, through intermediate
        # variables: first p_{m1} (variables v at t = 2, r at t ≥ 3), then p_{m2}. This gives exactly
        # the same LP, with coefficients that are single transition probabilities, as in order 1.
        # initial condition of order 2 (eq:order-k-initial), t = 2:
        #   v_{n1,d1,d2,κ'} = Σ_{b | A_G(b) = (d1,d2,κ')} p_{m1}(n1 | x0_{m1}, d1) μ1_b   (μ1 added by add_first_column!)
        #   Σ_a q^G_{(n1,n2,k),a,2} = Σ_{d1,d2,κ' | φ_1(k0,κ') = k} p_{m2}(n2 | x0_{m2}, d2) v_{n1,d1,d2,κ'}
        if H >= 2
            vv = Dict{NTuple{4,Int},VariableRef}()
            for n1 in S[m1][2], d1 in 1:2, d2 in 1:2, κp in qrange(k0[p])
                n1 == top(m1, 2) && continue
                vv[(n1, d1, d2, κp)] = @variable(model, lower_bound = 0)
                vfirst[(g, n1, d1, d2, κp)] = @constraint(model, 1.0 * vv[(n1, d1, d2, κp)] == 0)
            end
            for n1 in S[m1][2], n2 in S[m2][2], k in qrange(K0)
                (n1 == top(m1, 2) || n2 == top(m2, 2)) && continue
                rhs = AffExpr(0.0)
                for d1 in 1:2, d2 in 1:2, κp in qrange(k0[p])
                    quota_next(1, t0_cyc, k0[p], κp, K0) == k || continue
                    p2 = trans_prob(fd, m2, n2, x0[m2], d2)
                    p2 == 0.0 && continue
                    add_to_expression!(rhs, p2, vv[(n1, d1, d2, κp)])
                end
                pinit[(g, n1, n2, k)] = @constraint(model,
                    sum(qG[(g, n1, n2, k, d1, d2, κ, 2)] for d1 in 1:2, d2 in 1:2, κ in qrange(k)) == rhs)
            end
        end
        # flow of order 2 (eq:order-k-flow), t ≥ 3:
        #   r_{n1,n2',d1,d2,k,t} = Σ_{n1'} p_{m1}(n1 | n1', d1) Σ_{(k',κ') → k} q^G_{(n1',n2',k'),(d1,d2,κ'),t-1}
        #   Σ_a q^G_{(n1,n2,k),a,t} = Σ_{d1,d2,n2'} p_{m2}(n2 | n2', d2) r_{n1,n2',d1,d2,k,t}
        for t in 3:H, kn in qrange(K0)
            preds = quota_predecessors(t, t0_cyc, kn, K0)
            r = Dict{NTuple{4,Int},VariableRef}()
            if !isempty(preds)
                for n1 in S[m1][t], n2p in S[m2][t - 1], d1 in 1:2, d2 in 1:2
                    n1 == top(m1, t) && continue
                    rhs = AffExpr(0.0)
                    for n1p in S[m1][t - 1]
                        p1 = trans_prob(fd, m1, n1, n1p, d1)
                        p1 == 0.0 && continue
                        for (kp, κp) in preds
                            add_to_expression!(rhs, p1, qG[(g, n1p, n2p, kp, d1, d2, κp, t - 1)])
                        end
                    end
                    rv = @variable(model, lower_bound = 0)
                    @constraint(model, rv == rhs)
                    r[(n1, n2p, d1, d2)] = rv
                end
            end
            for n1 in S[m1][t], n2 in S[m2][t]
                (n1 == top(m1, t) || n2 == top(m2, t)) && continue
                lhs = sum(qG[(g, n1, n2, kn, d1, d2, κ, t)] for d1 in 1:2, d2 in 1:2, κ in qrange(kn))
                rhs = AffExpr(0.0)
                for (key, rv) in r
                    p2 = trans_prob(fd, m2, n2, key[2], key[4])
                    p2 == 0.0 || key[1] != n1 || add_to_expression!(rhs, p2, rv)
                end
                @constraint(model, lhs == rhs)
            end
        end
        for t in 2:H
            # consistency of order 2 (eq:order-k-action): Σ_{x_G} q^G_{x_G,a_G,t} = Σ_{b | A_G(b) = a_G} μ_{b,t}
            for d1 in 2:2, d2 in 2:2, κ in qrange(K0)
                pcons[(g, d1, d2, κ, t)] = @constraint(model,
                    sum(qG[(g, n1, n2, k, d1, d2, κ, t)] for n1 in S[m1][t], n2 in S[m2][t], k in κ:QUOTA_STEP:K0) == 0)
            end
            # marginalisation (eq:order-k-marg) onto each component of the pair (reachable states only
            # if `reduced`: the order-1 variables of the other states are 0 by the order-1 flow)
            for k in qrange(K0), κ in qrange(k)
                for n1 in S[m1][t], d1 in 1:2
                    @constraint(model, sum(qG[(g, n1, n2, k, d1, d2, κ, t)] for n2 in S[m2][t], d2 in 1:2) ==
                                       q[(m1, n1, d1, k, κ, t)])
                end
                for n2 in S[m2][t], d2 in 1:2
                    cyc && n2 == 1 && d2 == 1 && continue   # reduced: implied by the other pairs
                    @constraint(model, sum(qG[(g, n1, n2, k, d1, d2, κ, t)] for n1 in S[m1][t], d1 in 1:2) ==
                                       q[(m2, n2, d2, k, κ, t)])
                end
            end
        end
    end

    @objective(model, Min, obj)
    return PaperMaster(model, H, copy(x0), copy(k0), t0_cyc, first, init, cons, q,
                       VariableRef[], Column[], Vector{VariableRef}[], Column[],
                       copy(pairs), qG, pinit, vfirst, pcons, PaperCut[], lp_method)
end

"""
Solve the restricted master LP. The master LP is always feasible (the empty joint action), but
Gurobi's presolve occasionally declares it infeasible (observed on three_poles, with the columns
accumulated in the pools): it is then solved again with the barrier method, then without presolve,
then without presolve and with NumericFocus = 3. The default parameters are set again before every
solve (changing a parameter after a solve would discard its result).
The false infeasibility can also come from a desynchronisation between JuMP's copy of the master LP
and Gurobi's model, after many columns have been added (observed on two_poles with 2 threads, at
x = new, k = (30, 30), t0_cyc = 3: Gurobi finds an irreducible infeasible subsystem, while JuMP's
copy, written to a file or copied again into Gurobi, is optimal). The first fallback therefore
rebuilds Gurobi's model from JuMP's copy (MOI.Utilities.reset_optimizer).
"""
function solve_master!(master)   # PaperMaster, or LightMaster (fluid_light_cg_paper.jl)
    model = master.model
    for (attempt, params) in enumerate((["Method" => master.lp_method], ["Method" => master.lp_method],
                   ["Method" => 2],
                   ["Method" => master.lp_method, "Presolve" => 0],
                   ["Method" => master.lp_method, "Presolve" => 0, "NumericFocus" => 3]))
        attempt == 2 && MOI.Utilities.reset_optimizer(model)   # rebuild Gurobi's model from JuMP's copy
        set_optimizer_attribute(model, "Presolve", -1); set_optimizer_attribute(model, "NumericFocus", 0)
        for (name, val) in params
            set_optimizer_attribute(model, name, val)
        end
        optimize!(model)
        if is_solved_and_feasible(model; dual = true)
            attempt > 1 && println("  master LP solved after a numerical failure, attempt ", attempt, " ", params)
            return
        end
    end
    assert_is_solved_and_feasible(model; dual = true)
end

"Probability of the pair of local states (n1, n2) at t = 2 of the components m1, m2 when b is applied at t = 1."
pair_first_prob(fd::FluidData, master::PaperMaster, m1::Int, m2::Int, n1::Int, n2::Int, col::Column) =
    trans_prob(fd, m1, n1, master.x0[m1], column_mode(col, m1)) *
    trans_prob(fd, m2, n2, master.x0[m2], column_mode(col, m2))

"Quota at t = 2 of pole p when b is applied at t = 1."
first_next_k(fd::FluidData, master::PaperMaster, p::Int, col::Column) =
    quota_next(1, master.t0_cyc, master.k0[p], column_kappa(col, p), fd.K0[p])

"True iff the joint action b enters the right-hand side σ of the cut c (A_{m1}(b) = a1 or A_{m2}(b) = a2)."
cut_covers(fd::FluidData, c::PaperCut, col::Column) =
    column_kappa(col, fd.pole_of[c.m1]) == c.κ && (column_mode(col, c.m1) == c.d1 || column_mode(col, c.m2) == c.d2)

"Add the variable μ1_b of a first-step column b ∈ B(x0), with its true cost c⊗(x0, b)."
function add_first_column!(fd::FluidData, master::PaperMaster, col::Column)
    v = @variable(master.model, lower_bound = 0)
    set_objective_coefficient(master.model, v, first_step_cost(fd, master.x0, col))
    set_normalized_coefficient(master.first, v, 1.0)
    if master.H >= 2
        for m in 1:fd.M
            p = fd.pole_of[m]; mode = column_mode(col, m)
            k_next = first_next_k(fd, master, p, col)
            for n in 1:fd.n_states[m]
                prob = trans_prob(fd, m, n, master.x0[m], mode)
                (prob == 0.0 || !haskey(master.init, (m, n, k_next))) && continue   # row not written if reduced
                set_normalized_coefficient(master.init[(m, n, k_next)], v, -prob)
            end
        end
        for (g, (m1, m2)) in enumerate(master.pairs)
            d1 = column_mode(col, m1); d2 = column_mode(col, m2); κp = column_kappa(col, fd.pole_of[m1])
            for n1 in 1:(fd.n_states[m1] - 1)
                prob = trans_prob(fd, m1, n1, master.x0[m1], d1)
                (prob == 0.0 || !haskey(master.vfirst, (g, n1, d1, d2, κp))) && continue   # unreachable if reduced
                set_normalized_coefficient(master.vfirst[(g, n1, d1, d2, κp)], v, -prob)
            end
        end
        for c in master.cuts   # t = 2 cuts: exact joint distribution of the pair, in μ1
            c.t == 2 || continue
            c.k == first_next_k(fd, master, fd.pole_of[c.m1], col) || continue
            prob = pair_first_prob(fd, master, c.m1, c.m2, c.n1, c.n2, col)
            prob == 0.0 && continue
            set_normalized_coefficient(c.con, v, -prob)
        end
    end
    push!(master.μ1, v); push!(master.cols1, col)
end

"Add the variables μ_{b,t}, t = 2..H, of a column b ∈ B, with the joint action cost f(b)."
function add_column_paper!(fd::FluidData, master::PaperMaster, col::Column)
    f = column_penalty(fd, col)
    vars = VariableRef[]
    for t in 2:master.H
        v = @variable(master.model, lower_bound = 0)
        set_objective_coefficient(master.model, v, f)
        for p in 1:fd.inst.n_poles
            κ = column_kappa(col, p)
            for m in fd.comps_of_pole[p]
                key = (m, column_mode(col, m), κ, t)   # row not written if reduced
                haskey(master.cons, key) && set_normalized_coefficient(master.cons[key], v, -1.0)
            end
        end
        for (g, (m1, m2)) in enumerate(master.pairs)
            κ = column_kappa(col, fd.pole_of[m1])
            key = (g, column_mode(col, m1), column_mode(col, m2), κ, t)
            haskey(master.pcons, key) && set_normalized_coefficient(master.pcons[key], v, -1.0)
        end
        for c in master.cuts
            c.t == t && cut_covers(fd, c, col) && set_normalized_coefficient(c.con, v, -1.0)
        end
        push!(vars, v)
    end
    push!(master.μ, vars); push!(master.cols, col)
end

